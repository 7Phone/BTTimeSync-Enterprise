    /// 调试信息。
    /// </summary>
    Debug,

    /// <summary>
    /// 一般运行信息。
    /// </summary>
    Information,

    /// <summary>
    /// 警告信息。
    /// </summary>
    Warning,

    /// <summary>
    /// 错误信息。
    /// </summary>
    Error,

    /// <summary>
    /// 严重错误。
    /// </summary>
    Critical
}